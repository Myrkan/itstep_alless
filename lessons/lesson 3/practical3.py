# Завдання 6
# Щоб спекти пиріг потрібно 4 яблука та 1.2 літра молока.
# Користувач вводить кількість яблук та молока(у літрах).
# Виведіть скільки він може спекти пирогів.
# Виведіть скільки яблук та молока залишиться.
# Приклад:
# Введіть кількість яблук: 5
# Введіть кількість молока (л): 10
# Можна спекти пирогів: 1
# Залишиться яблук: 1
# Залишиться молока: 8.8

apples = int(input("Введите количество яблок:"))
milk = float(input("Введите количество молока (в литрах):"))

apples_per_pie = 4
milk_per_pie = 1.2

pies_by_apples = apples // apples_per_pie

pies_by_milk = milk // milk_per_pie

pies = int(min(pies_by_apples, pies_by_milk))

remaining_apples = apples - (pies * apples_per_pie)
remaining_milk = milk - (pies * milk_per_pie)

print(f"Можно испечь пирогов: {pies}")
print(f"Останется яблок: {remaining_apples}")
print(f"Останется молока: {remaining_milk}")

