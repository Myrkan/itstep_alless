# Завдання 3
# Користувач вводить довжину в метрах. Покажіть її у
# ● Ярдах(1 ярд = 0,9144 метра)
# ● Футах(1 фут = 0,3048 метра)
# В кінці спитайте користувача чи продовжувати роботу програми.

yards = 0.9144
feet = 0.3048

while True:
    length_meters = float(input("Введите длину в метрах: "))

    yard = length_meters / yards
    foot = length_meters / feet

    print(f"{length_meters} метров это: \n{yard:.2f} ярдов и {foot:.2f} футов")

    go = input("Продолжить? да/нет")

    if go == "нет":
        break

print("Программа завершена.")

# Завдання 4
# У завданні 2 ще виведіть кількість днів за яку була
# зібрана потрібна сума.

total = 0
days = 0
goal = float(input("Цільова сума? "))
while True:
    daily_amount = float(input("Сьогоднішній вклад? "))
    total += daily_amount
    days += 1

    if total >= goal:
     break

print(f"Мету досягнуто! У скарбничці {total} грн.")
print(f"Нужная сумма была собрана за {days} дней.")

