# Завдання 6
# Напишіть програму для введення пароля від банкомату.
# У користувача є лише три спроби
# В кінці виведіть чи вдалось правильно ввести пароль

password = "1223"
attempts = 0
count = 3
while attempts < 3:
    answer_pin = input("Введите PIN:")
    attempts += 1

    if answer_pin == password:
        print("Введен правильный ПИН")
        break
    else:
        count -= 1
        print("Попробуйте еще раз")
        print(f"Осталось {count} попытки")

if answer_pin == password:
    print("Доступ разрешен")
else:
    print(f"Доступ запрещен осталось {count} попыток ")


